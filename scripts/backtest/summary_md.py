"""Render the backtest results into a markdown summary for docs/."""

from __future__ import annotations

import json
import math
from pathlib import Path


def f(x, d=2, pct=False, sign=False):
    if x is None:
        return "—"
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "—"
    if not math.isfinite(v):
        return "—"
    if pct:
        v *= 100
    s = f"{v:+.{d}f}" if sign else f"{v:.{d}f}"
    return s + ("%" if pct else "")


def md_table(headers, rows):
    def cell(v):
        return str(v).replace("|", "\\|")

    out = ["| " + " | ".join(cell(h) for h in headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(cell(c) for c in r) + " |")
    return "\n".join(out)


def build(payload: dict) -> str:
    results = payload["results"]
    meta = payload["meta"]
    parts: list[str] = []

    parts.append(
        "# Screener filter combination backtest — US & HK\n\n"
        "Generated by `scripts/backtest/run_backtest.py`. Every combination of the 7 screener "
        "filters (single filter, or 2–3 filters combined) was replayed over the full price "
        "history in the production Supabase database.\n"
    )

    for market in ("US", "HK"):
        mm = meta[market]
        b = mm["benchmark"]
        bn = mm.get("benchmark_net", {})
        rows = [r for r in results if r["market"] == market]
        cred = [r for r in rows if r.get("credible")]
        pos = [r for r in cred if (r["sharpe"] or 0) > 0 and (r["cagr"] or 0) > 0]
        oos = [r for r in pos if (r["oos_sharpe"] or 0) > 0]
        stable = [r for r in oos
                  if (r["seg1_sharpe"] or 0) > 0 and (r["seg2_sharpe"] or 0) > 0
                  and (r["seg3_sharpe"] or 0) > 0]

        parts.append(f"\n## {market}\n")
        parts.append(
            f"- **Universe**: {mm['n_stocks']} active stocks · {mm['first_date']} → {mm['last_date']} "
            f"({mm['n_dates']} sessions)\n"
            f"- **Benchmark** (equal-weight universe, monthly rebalance): Sharpe **{f(b['sharpe'])}**, "
            f"CAGR **{f(b['cagr'] * 100, 1)}%**, maxDD **{f(b['max_dd'] * 100, 1)}%**, "
            f"hit {f(b['hit_rate'] * 100, 0)}%, {b['n_periods']} periods "
            f"(net of 25bp round trip: Sharpe {f(bn.get('sharpe'))}, CAGR {f((bn.get('cagr') or 0) * 100, 1)}%)\n"
            f"- **Combinations tested**: {len(rows)} (1–3 filters × 3 values each) · "
            f"{len(cred)} statistically usable · {len(pos)} positive on both Sharpe and CAGR · "
            f"{len(oos)} of those still positive out-of-sample · {len(stable)} positive in all three sub-periods\n"
            f"- **Out-of-sample window**: {mm['oos_start']} → {mm['last_date']} ({mm['oos_periods']} periods)"
        )

        # singles
        singles = sorted([r for r in rows if r["n_filters"] == 1],
                         key=lambda r: (r["sharpe"] if r["sharpe"] is not None else -99), reverse=True)
        parts.append("\n### Single filters (7 × 3)\n")
        parts.append(md_table(
            ["Filter", "Sharpe", "Sharpe net", "CAGR", "MaxDD", "Hit%", "Avg names",
             "Alpha/mo", "t-stat", "OOS Sharpe"],
            [[r["combo"], f(r["sharpe"]), f(r.get("net_sharpe")), f((r["cagr"] or 0) * 100, 1) + "%",
              f((r["max_dd"] or 0) * 100, 1) + "%", f((r["hit_rate"] or 0) * 100, 0) + "%",
              f(r["avg_picks"], 1), f((r.get("alpha_fwd21") or 0) * 100, 2) + "%",
              f(r["t_stat"], 1), f(r["oos_sharpe"])] for r in singles],
        ))

        # top combos
        top = sorted(stable, key=lambda r: r.get("net_sharpe") or -99, reverse=True)[:20]
        parts.append("\n### Best combinations (positive, stable, net of costs)\n")
        parts.append(md_table(
            ["#F", "Combination", "Sharpe", "Sharpe net", "CAGR", "CAGR net", "MaxDD", "Hit%",
             "Avg names", "Alpha/mo", "OOS Sharpe", "Seg 1", "Seg 2", "Seg 3"],
            [[r["n_filters"], r["combo"], f(r["sharpe"]), f(r.get("net_sharpe")),
              f((r["cagr"] or 0) * 100, 1) + "%", f((r.get("net_cagr") or 0) * 100, 1) + "%",
              f((r["max_dd"] or 0) * 100, 1) + "%", f((r["hit_rate"] or 0) * 100, 0) + "%",
              f(r["avg_picks"], 1), f((r.get("alpha_fwd21") or 0) * 100, 2) + "%",
              f(r["oos_sharpe"]), f(r["seg1_sharpe"]), f(r["seg2_sharpe"]), f(r["seg3_sharpe"])]
             for r in top],
        ))

        # filter pair winners
        parts.append("\n### Best value-combination per filter pair\n")
        seen = set()
        pair_rows = []
        for r in sorted([x for x in rows if x["n_filters"] == 2 and x.get("credible")],
                        key=lambda x: (x["sharpe"] if x["sharpe"] is not None else -99), reverse=True):
            key = tuple(sorted(x.split(" ")[0] for x in r["combo"].split(" AND ")))
            if key in seen:
                continue
            seen.add(key)
            pair_rows.append([r["combo"], f(r["sharpe"]), f(r.get("net_sharpe")),
                              f((r["cagr"] or 0) * 100, 1) + "%", f(r["avg_picks"], 1),
                              f((r.get("alpha_fwd21") or 0) * 100, 2) + "%", f(r["oos_sharpe"])])
        parts.append(md_table(
            ["Best pair combination", "Sharpe", "Sharpe net", "CAGR", "Avg names", "Alpha/mo", "OOS Sharpe"],
            pair_rows,
        ))

    parts.append(
        "\n## Method\n\n"
        "- Indicators use the production formulas from "
        "`workers/yfinance/src/eyesinvest_worker/providers/analytics.py`; filter comparisons mirror "
        "`apps/web/src/lib/stocks/queries.ts :: applyScreenerFilters` (nulls never match, "
        "the `>` / `<` boundaries follow the live dropdowns).\n"
        "- Signal at close T → entry at the close of T+1 → exit 21 sessions later. Equal weight, "
        "rebalanced every 21 sessions, no overlap between periods.\n"
        "- The squeeze score is rebuilt point-in-time for every date (from the short-interest "
        "settlement known on that date) instead of the production worker's habit of writing "
        "today's score onto every historical row. The HK morning-session component is dropped "
        "because AM short volume only exists from 2026-08.\n"
        "- `Alpha/mo` = average 21-session forward return of the picks minus the same figure for "
        "the whole market universe.\n"
        "- `Seg 1/2/3` = Sharpe over three equal sub-periods — a stable edge is positive in all three.\n"
        "- **Credibility gate**: ≥5 names in the basket on a typical rebalance, ≥12 monthly "
        "periods with a position, ≥500 stock-level observations.\n"
        "- **Multiple testing**: 2,310 combinations were scored. A positive Sharpe alone is not "
        "evidence of edge — read the out-of-sample and segment columns together.\n"
        "- **Caveats**: survivorship bias (currently active stocks only), 2023-08 → 2026-10 window, "
        "no liquidity or market-cap screen, max drawdown measured on monthly closes only.\n"
    )
    return "\n".join(parts)


def main() -> int:
    root = Path(__file__).resolve().parents[2]
    payload = json.loads((Path(__file__).resolve().parent / "out" / "results.json").read_text())
    out = root / "docs" / "BACKTEST_FILTER_COMBINATIONS.md"
    out.write_text(build(payload), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
